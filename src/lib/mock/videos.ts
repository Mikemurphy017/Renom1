function metricsFor(seed: number, platforms: PlatformId[], scale: number): PlatformMetrics[] {
  const r = seeded(seed);
  const weight: Record<PlatformId, number> = { youtube: 1.1, youtube_shorts: 1.5, instagram: 1.2, tiktok: 1.3, facebook: 0.5, linkedin: 0.7, x: 0.3 };
  return platforms.map((p) => {
    const views = Math.round(scale * weight[p] * (0.7 + r() * 0.6));
    const long = p === "youtube" || p === "linkedin";
    return {
      platform: p,
      views,
      watchTimeSec: Math.round((long ? 210 : 28) * (0.75 + r() * 0.4)),
      engagementRate: +(2.2 + r() * (p === "linkedin" ? 5 : 3.2)).toFixed(1),
      followers: Math.round(views * (0.004 + r() * 0.006)),
      linkClicks: Math.round(views * (p === "linkedin" ? 0.018 : 0.006) * (0.6 + r())),
      inquiries: Math.round(views * (p === "linkedin" ? 0.0009 : 0.0003) * (0.5 + r())),
    };
  });
}

